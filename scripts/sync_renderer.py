#!/usr/bin/env python3
"""Make every skill self-contained for deliverable generation.

Each skill folder must work when it is loaded on its own — into a GrokBot
agent, a Claude project, a zip upload — so each one carries:

  scripts/ma_render.py     byte-identical copy of shared/ma_render/ma_render.py
  scripts/requirements.txt the python packages its scripts use
  SKILL.md                 a generated "Deliverable format" section (between
                           the ma-render markers) naming the file types it
                           delivers and the exact commands to build them
  metadata.deliverables    the same file types, machine-readable

The canonical engine and the per-skill profile table live here, so there is
one place to change. CI runs --check and fails on any drift.

    python3 scripts/sync_renderer.py            # write copies and sections
    python3 scripts/sync_renderer.py --check    # verify, change nothing
"""

